// Generates docs/TOOLS.md (tool reference) from the bundled OpenAPI spec.
// Usage: node scripts/gen-docs.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { buildTools, groupNames } from "../src/tools.js";

const tools = buildTools({ readOnly: false, excludeAudits: false, groups: [], exclude: [], compact: true });
const byGroup = new Map();
for (const t of tools.values()) {
  if (!byGroup.has(t.group)) byGroup.set(t.group, []);
  byGroup.get(t.group).push(t);
}

const order = [...groupNames(), ...[...byGroup.keys()].filter((g) => !groupNames().includes(g))];
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");

let md = `# Tool reference

Generated by \`node scripts/gen-docs.mjs\` from the Contabo OpenAPI spec. **${tools.size} tools** in ${byGroup.size} groups.

Legend: 🔍 read-only (GET) · ✏️ changes data (POST/PUT/PATCH) · 🗑️ destructive (DELETE).
Use the group name (lower-case) in \`CONTABO_GROUPS\` to load only that group, e.g. \`CONTABO_GROUPS=dns,firewalls\`.

`;
md += order.filter((g) => byGroup.has(g)).map((g) => `- [${g}](#${slug(g)}) (${byGroup.get(g).length})`).join("\n") + "\n";

for (const g of order) {
  if (!byGroup.has(g)) continue;
  md += `\n## ${g}\n\n| Tool | | Endpoint | Description |\n|---|---|---|---|\n`;
  for (const t of byGroup.get(g)) {
    const icon = t.method === "get" ? "🔍" : t.method === "delete" ? "🗑️" : "✏️";
    const args = Object.entries(t.def.inputSchema.properties).filter(([k]) => k !== "x-trace-id");
    const req = new Set(t.def.inputSchema.required || []);
    const argList = args.map(([k]) => (req.has(k) ? `**${k}**` : k)).join(", ");
    md += `| \`${t.def.name}\` | ${icon} | \`${t.method.toUpperCase()} ${t.path}\` | ${t.summary.replace(/\|/g, "\\|")}${
      argList ? `<br><sub>args: ${argList}</sub>` : ""
    } |\n`;
  }
}
md += "\nBold arguments are required.\n";

mkdirSync(new URL("../docs/", import.meta.url), { recursive: true });
writeFileSync(new URL("../docs/TOOLS.md", import.meta.url), md);
console.log(`docs/TOOLS.md written (${tools.size} tools)`);
